CREATE TABLE contracts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code    VARCHAR(20)  NOT NULL,
    country          VARCHAR(2)   NOT NULL,
    valid_from       DATE         NOT NULL,
    valid_to         DATE         NOT NULL,
    pending_valid_to DATE,
    status           VARCHAR(20)  NOT NULL,
    rejection_reason VARCHAR(255),
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    CONSTRAINT ck_contracts_validity CHECK (valid_from <= valid_to)
);

CREATE INDEX idx_contracts_customer_country ON contracts (customer_code, country);
CREATE INDEX idx_contracts_status ON contracts (status);

CREATE TABLE contract_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id   BIGINT         NOT NULL,
    material_code VARCHAR(20)    NOT NULL,
    quantity      NUMERIC(19, 4) NOT NULL,
    unit_price    NUMERIC(19, 4) NOT NULL,
    CONSTRAINT fk_contract_items_contract FOREIGN KEY (contract_id) REFERENCES contracts (id)
);

CREATE INDEX idx_contract_items_contract ON contract_items (contract_id);

CREATE TABLE price_conditions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_type VARCHAR(20)   NOT NULL,
    country       VARCHAR(2)     NOT NULL,
    customer_code VARCHAR(20),
    material_code VARCHAR(20)    NOT NULL,
    amount        NUMERIC(19, 4) NOT NULL,
    valid_from    DATE           NOT NULL,
    valid_to      DATE           NOT NULL,
    created_at    TIMESTAMP      NOT NULL,
    CONSTRAINT ck_price_conditions_validity CHECK (valid_from <= valid_to)
);

CREATE INDEX idx_price_conditions_lookup ON price_conditions (country, material_code, valid_from, valid_to);
